#!/usr/bin/env python3
"""
build_docs.py — War of Princes' pages (campaign/docs/) → campaign/data/docs.js and docs.css.

    python3 campaign/build/build_docs.py

The docs are the campaign site's pages as they were moved into the VTT (campaign/build/
move_pages.py) and written since: one HTML fragment per site tab, and the stylesheets they were
drawn with. This writes

  campaign/data/docs.js   window.WopDocs = { <tab>: "<html>" … } - the fragments, as they are
  campaign/data/docs.css  the stylesheets, each rule scoped to the element a doc is drawn into

Scoping is what keeps the old site's styles off the VTT: both define the same custom properties
(--ink, --blood, --rule) and style html and body. envoy.css, the old site's shared sheet, is
scoped to `.wop-envoy`, the class every doc but the household carries (the household page never
loaded it); a doc's own sheet (campaign/docs/<tab>.css) to `.doc-<tab>`. `:root`, `html` and
`body` become the scope itself.

It fails (exit 1) on anything a tab would show wrong: a link that is not a tab of the site or an
outside address, an image that is not on disk, a doc no tab draws, or a scoped rule whose selector
escapes its scope.
"""
import json
import os
import re
import sys

CAMPAIGN = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(CAMPAIGN)
DOCS = os.path.join(CAMPAIGN, "docs")
OUT_JS = os.path.join(CAMPAIGN, "data", "docs.js")
OUT_CSS = os.path.join(CAMPAIGN, "data", "docs.css")

TABS = ["home", "setting", "coterie", "people", "chronicle", "household"]   # campaign/site/site.js
ENVOY_SCOPE = ".wop-envoy"

errors = []


def split_rules(css):
    """Top-level blocks of a stylesheet: (prelude, body) pairs, @media bodies left whole."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j == -1:
            break
        depth, k = 1, j + 1
        while k < n and depth:
            depth += {"{": 1, "}": -1}.get(css[k], 0)
            k += 1
        out.append((css[i:j].strip(), css[j + 1:k - 1]))
        i = k
    return out


def scope_selector(sel, scope):
    sel = sel.strip()
    if sel in (":root", "html", "body"):
        return scope
    if sel == "*":
        return scope + " *"
    m = re.match(r"^(html|body)\b(.*)$", sel)
    if m:
        return scope + m.group(2)
    return scope + " " + sel


def scope_css(css, scope, src):
    out = []
    for prelude, body in split_rules(css):
        if prelude.startswith("@media") or prelude.startswith("@supports"):
            out.append("%s {\n%s}" % (prelude, scope_css(body, scope, src)))
        elif prelude.startswith("@keyframes") or prelude.startswith("@font-face"):
            out.append("%s {%s}" % (prelude, body))
        elif prelude.startswith("@"):
            errors.append("%s: an at-rule this build does not scope: %s" % (src, prelude[:40]))
        else:
            sels = [scope_selector(s, scope) for s in prelude.split(",")]
            out.append("%s {%s}" % (",\n".join(sels), body))
    return "\n".join(out) + "\n"


def check_scoped(css, scopes):
    for prelude, body in split_rules(css):
        if prelude.startswith("@media") or prelude.startswith("@supports"):
            check_scoped(body, scopes)
        elif not prelude.startswith("@"):
            for s in prelude.split(","):
                if not any(s.strip() == sc or s.strip().startswith(sc + " ") or s.strip().startswith(sc + ":") or s.strip().startswith(sc + ".")
                           for sc in scopes):
                    errors.append("docs.css: a selector escapes its scope: %r" % s.strip())


def main():
    docs = {}
    for f in sorted(os.listdir(DOCS)):
        if f.endswith(".html"):
            docs[f[:-5]] = open(os.path.join(DOCS, f), encoding="utf-8").read()
    for d in docs:
        if d not in TABS:
            errors.append("campaign/docs/%s.html: no tab draws it" % d)
    for t in TABS:
        if t not in docs:
            errors.append("tab %s: campaign/docs/%s.html is missing" % (t, t))
    for d, html in docs.items():
        for h in re.findall(r'href="([^"]*)"', html):
            if not (re.match(r"^https?:", h) or h[1:].split("/")[0] in TABS and h.startswith("#")):
                errors.append("%s: link %r is not a tab of the site" % (d, h))
        for s in re.findall(r'src="([^"]*)"', html):
            if not os.path.isfile(os.path.join(ROOT, s)):
                errors.append("%s: image %r is not on disk" % (d, s))

    parts = ["/* Generated by campaign/build/build_docs.py from campaign/docs/*.css - do not edit by hand. */\n"]
    scopes = [ENVOY_SCOPE]
    parts.append(scope_css(open(os.path.join(DOCS, "envoy.css"), encoding="utf-8").read(), ENVOY_SCOPE, "envoy.css"))
    for t in TABS:
        p = os.path.join(DOCS, t + ".css")
        if os.path.exists(p):
            parts.append(scope_css(open(p, encoding="utf-8").read(), ".doc-" + t, t + ".css"))
            scopes.append(".doc-" + t)
    css = "\n".join(parts)
    check_scoped(css, scopes)

    if errors:
        for e in errors:
            print("  FAIL " + e)
        print("build_docs: FAILED (%d)" % len(errors))
        return 1
    with open(OUT_JS, "w", encoding="utf-8") as fh:
        fh.write("/* Generated by campaign/build/build_docs.py from campaign/docs/*.html - do not edit by hand. */\n")
        fh.write("window.WopDocs = %s;\n" % json.dumps(docs, ensure_ascii=False))
    with open(OUT_CSS, "w", encoding="utf-8") as fh:
        fh.write(css)
    print("build_docs: %d docs → campaign/data/docs.js; %d stylesheets scoped → campaign/data/docs.css" % (len(docs), len(scopes)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
