#!/usr/bin/env python3
"""
build_layer.py — an instance's own DSL layer (its homebrew: NPCs, characters, house rules as
MODIFYs, lore) built as one more book, and gated as the books are.

    python3 build/build_layer.py <layer dir> --id campaign --label "Blood & Other Drugs" --out campaign/data

An instance is a campaign repo forked from this VTT (PLAN.md, "Instances"); its layer lives in
its own folder and never in data/. This writes two files into --out:

  <id>.js    the layer's entities — a self-registering book file, loaded on demand like any book
  index.js   the layer's index record, its records and its corrections, merged ahead of the
             corpus's at the `data` stage (engine/instance.js), so every list view leads with
             the layer and a house rule shows beside the rule it changes

then gates them, and exits non-zero on any failure:

  1. COVERAGE and FIDELITY, by count — verify_data.py's rule over the layer's own files: every
     string the layer prints reaches its data as often as it is printed, and nothing in the
     data came from anywhere else.
  2. IDS — no entity of the layer takes an id the corpus uses.
  3. REFERENCES — every id the layer points at (the type a DEF EXTENDS, a LIST OF type, a
     reference, a MODIFY's target, any hash argument) is an entity of the layer or of the
     corpus. A homebrew NPC built on a mistyped chassis fails here, not at the table.
  4. NAMES — a reference with no hash must name an entity of the layer or the corpus. This
     corpus leaves many entities unhashed and names them bare where it points at them, so a
     bare name is ordinary; a name that matches nothing is a fault, and a name that matches
     several is reported with the one the pages will resolve it to (the layer's own first,
     then the core's — system/vtm5e/data.js).

The corpus side is read from data/*.js, so the books must be built first (build/build.sh).
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_data import (BANNER as DATA_BANNER, DSL_EXTS, KINDS, LORE_EXTS, RECORD_FIELDS,  # noqa: E402,F401
                        SHAPE_NAMES, collect_entities, corrections_of, first_page, kwstr,
                        lore_chapter, records_of)
from parse_dsl import parse_files  # noqa: E402
from verify_data import BLOB, TYPE_WORDS, corpus_strings, data_strings  # noqa: E402

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KIND = "campaign"
LAYER_BLOB = re.compile(r"var d=(\{.*\});var T=window\.VTM5E", re.S)

BANNER = ("/* Generated by build/build_layer.py from this instance's DSL layer — do not edit by hand.\n"
          "   Every string is verbatim from the layer's files; regenerate rather than patch. */\n")
REGISTER = """(function(){var d=%s;var T=window.VTM5E=window.VTM5E||{books:{},entities:{},loaded:{}};
T.loaded[d.src]=true;T.books[d.book.id]=d.book;
for(var h in d.entities){T.entities[h]=d.entities[h];}})();
"""
# Merged into the corpus's index, records and corrections, FIRST — the shelf shelves the campaign
# first and every list view (the Storyteller characters, the Cast, the powers) leads with the
# campaign's own rather than sitting after eighteen books of published ones. Replaces its own
# earlier copy, so a reload is a no-op.
INDEX = """(function(){var d=%s;var T=window.VTM5E=window.VTM5E||{books:{},entities:{},loaded:{}};
var I=T.index=T.index||{books:[],counts:{}};I.counts=I.counts||{};
var had=(I.books||[]).some(function(b){return b.id===d.book.id;});
I.books=(I.books||[]).filter(function(b){return b.id!==d.book.id;});I.books.unshift(d.book);
if(!had){I.counts.books=(I.counts.books||0)+1;I.counts.entities=(I.counts.entities||0)+d.book.counts.entities;
I.counts.files=(I.counts.files||0)+d.book.counts.chapters;
var R=I.counts.records=I.counts.records||{};d.records.forEach(function(r){R[r.kind]=(R[r.kind]||0)+1;});}
I.corrections=d.corrections.concat((I.corrections||[]).filter(function(c){return c.book!==d.book.id;}));
T.records=d.records.concat((T.records||[]).filter(function(r){return r.book!==d.book.id;}));})();
"""


def layer_files(root):
    out = []
    for dirpath, _dirs, files in os.walk(root):
        for fn in files:
            if fn.endswith(DSL_EXTS + LORE_EXTS) and not fn.startswith("."):
                out.append(os.path.relpath(os.path.join(dirpath, fn), root))
    return sorted(out)


def corpus_side():
    """What the built books carry: id -> (name, book), and the Discipline names the index
    records. The layer's records are read by the same shapes as the corpus's, and a power's
    Discipline is one of the corpus's own."""
    ents, disciplines = {}, set()
    data_dir = os.path.join(HERE, "data")
    if not os.path.isdir(data_dir):
        raise SystemExit("build_layer: no data/ — run build/build.sh first")
    for fn in sorted(os.listdir(data_dir)):
        if not fn.endswith(".js"):
            continue
        src = open(os.path.join(data_dir, fn), encoding="utf-8").read()
        m = BLOB.search(src)
        if m:
            for h, e in json.loads(m.group(1))["entities"].items():
                ents[h] = (e.get("name"), e.get("book"))
        elif fn == "index.js":
            m = re.search(r"T\.index=(\{.*\});\}\)\(\);", src, re.S)
            if m:
                disciplines = set(json.loads(m.group(1)).get("disciplines") or [])
    if not ents:
        raise SystemExit("build_layer: no book data in data/ — run build/build.sh first")
    return ents, disciplines


def pointed_at(node, out):
    """Every id a layer entity points at: typeHash, ofHash, a reference's hash, a hash arg."""
    if isinstance(node, dict):
        for k, v in node.items():
            if k in ("typeHash", "ofHash", "hash", "h") and isinstance(v, str) and v:
                out.add(v)
            else:
                pointed_at(v, out)
    elif isinstance(node, list):
        for x in node:
            pointed_at(x, out)
    return out


def hashed_pairs(node, out, where="?"):
    """Every place the layer names an id AND a name side by side — `#hash ^"Name"` in a
    REFERENCES line, an EXTENDS, a REF property, a LIST OF item, a MODIFY target: (where,
    hash, name). The pair is two claims about one entity, and both have to hold."""
    if isinstance(node, dict):
        here = node.get("id") if isinstance(node.get("id"), str) and node.get("name") else where
        if isinstance(node.get("hash"), str) and node["hash"] and isinstance(node.get("name"), str) and node["name"]:
            out.append((where, node["hash"], node["name"]))
        if isinstance(node.get("typeHash"), str) and node["typeHash"] and isinstance(node.get("type"), str) and node["type"]:
            out.append((here, node["typeHash"], node["type"]))
        for k, v in node.items():
            if k not in ("hash", "typeHash"):
                hashed_pairs(v, out, here)
    elif isinstance(node, list):
        for x in node:
            hashed_pairs(x, out, where)
    return out


def named_refs(entities, corrections, layer_id):
    """Every reference the layer makes by name alone: (where, name). Only the places a name
    can BE a reference are read — a DEF's EXTENDS, a LIST OF's element type, a REF property,
    a REFERENCES line and a MODIFY / OVERRIDE target. A scalar property's `type` is the type
    word STRING / INTEGER, never a reference, and is not read here."""
    out = []

    def ref(where, name, hashed):
        if isinstance(name, str) and name and not hashed:
            out.append((where, name))

    def prop(where, p):
        if p.get("vk") == "list":
            ref(where, p.get("of"), p.get("ofHash"))
            for it in p.get("items", []):
                if isinstance(it, dict) and it.get("vk") == "ref":
                    ref(where, it.get("name"), it.get("hash"))
        elif p.get("vk") == "ref":
            r = p.get("ref") or p
            ref(where, r.get("name"), r.get("hash"))
        elif p.get("vk") == "def":
            ref(where, p.get("type"), p.get("typeHash"))
            for f in p.get("fields", []):
                prop(where, f)

    for e in (entities or {}).values():
        where = e.get("name") or layer_id
        ref(where, e.get("type"), e.get("typeHash"))          # EXTENDS
        for p in e.get("props", []):
            prop(where, p)
        for r in e.get("refs", []):                            # §5c REFERENCES
            ref(where, r.get("name"), r.get("hash"))
    for c in corrections or []:
        t = c.get("target") or {}
        ref("%s in %s" % (c.get("op", "MODIFY"), c.get("file", "the layer")), t.get("name"), t.get("hash"))
        for p in c.get("props", []):
            prop("%s target %s" % (c.get("op", "MODIFY"), t.get("name")), p)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("layer", help="the instance's DSL layer folder")
    ap.add_argument("--id", required=True, help="the layer's book id (e.g. campaign)")
    ap.add_argument("--label", required=True, help="the layer's title on the shelf")
    ap.add_argument("--out", required=True, help="where the two files go, relative to the site root")
    a = ap.parse_args()

    root = os.path.abspath(a.layer)
    rels = layer_files(root)
    if not rels:
        raise SystemExit("build_layer: no DSL or .lore files under %s" % a.layer)
    out_dir = os.path.abspath(a.out)
    os.makedirs(out_dir, exist_ok=True)
    book_path = os.path.join(out_dir, "%s.js" % a.id)
    src = os.path.relpath(book_path, HERE).replace(os.sep, "/")
    if src.startswith(".."):
        print("build_layer: note — %s lies outside the site, so no page can load it (fine for a test build)" % a.out)

    # ── build: one book, by build_data.py's own walk ─────────────────
    chapters = []
    for rel in rels:
        path = os.path.join(root, rel)
        if rel.endswith(LORE_EXTS):
            chapters.append(lore_chapter(path, rel))
            continue
        chapters.append({"file": rel, "kind": "ttrpg", "page": first_page(path, False), "_path": path})
    chapters.sort(key=lambda c: (c["page"] is None, c["page"] or 0, c["file"]))

    entities, orders, roots, corrections = {}, [], [], []
    for c in chapters:
        if c["kind"] != "ttrpg":
            continue
        doc = parse_files([c.pop("_path")])[0]
        order = []
        c["container"] = doc["container"]
        c["name"] = kwstr(doc["body"], "NAME")
        c["roots"] = collect_entities(doc, a.id, entities, order)
        corrections.extend(corrections_of(doc, a.id))
        roots.extend(c["roots"])
        orders.append((c["file"], order))

    corpus_all, disciplines = corpus_side()
    records = records_of(entities, orders, disciplines)

    rec = {"id": a.id, "label": a.label, "kind": KIND, "chapters": chapters, "entities": roots}
    with open(book_path, "w", encoding="utf-8") as fh:
        fh.write(BANNER)
        fh.write(REGISTER % json.dumps({"src": src, "book": rec, "entities": entities},
                                       ensure_ascii=False, sort_keys=True))
    counts = {"entities": len(entities), "chapters": len(chapters)}
    for k in SHAPE_NAMES:
        counts[k] = sum(1 for r in records if r["kind"] == k)
    index_rec = {
        "id": a.id, "label": a.label, "kind": KIND, "files": {"main": [src]},
        "chapters": [{"file": c["file"], "kind": c["kind"], "name": c.get("name"), "page": c["page"]}
                     for c in chapters],
        "counts": counts,
        "bytes": os.path.getsize(book_path),
    }
    with open(os.path.join(out_dir, "index.js"), "w", encoding="utf-8") as fh:
        fh.write(BANNER)
        fh.write(INDEX % json.dumps({"book": index_rec, "records": records, "corrections": corrections},
                                    ensure_ascii=False, sort_keys=True))
    print("build_layer: %d files → %s/%s.js (%d entities, %d records, %d corrections) and index.js"
          % (len(rels), a.out, a.id, len(entities), len(records), len(corrections)))

    # ── gates, read back from the files as written ───────────────────
    fail = 0
    want, skipped = corpus_strings(os.path.join(root, r) for r in rels)
    book_blob = json.loads(LAYER_BLOB.search(open(book_path, encoding="utf-8").read()).group(1))
    index_blob = json.loads(LAYER_BLOB.search(open(os.path.join(out_dir, "index.js"), encoding="utf-8").read()).group(1))
    everywhere = data_strings([book_blob]) + data_strings([index_blob])
    ours = set(TYPE_WORDS) | set(KINDS) | {KIND, a.label, src} | set(SHAPE_NAMES)
    missing = sorted(k for k in want if k not in everywhere)
    short = sorted(k for k in want if k in everywhere and everywhere[k] < want[k])
    unsourced = sorted(k for k in everywhere if k not in want and k not in ours and k not in skipped)
    for label, rows in (("UNCOVERED — in the layer, not in its data", missing),
                        ("SHORT — printed more often than the data carries it", short),
                        ("UNSOURCED — in the data, not in the layer", unsourced)):
        if rows:
            fail = 1
            print("  %s: %d" % (label, len(rows)))
            for s in rows[:25]:
                print("    %r" % s[:130])
    if not (missing or short or unsourced):
        print("  strings: %d (%d occurrences) — 0 uncovered · 0 short · 0 unsourced"
              % (len(want), sum(want.values())))

    corpus = set(corpus_all)
    taken = sorted(set(entities) & corpus)
    if taken:
        fail = 1
        print("  IDS — the layer reuses %d corpus ids: %s" % (len(taken), ", ".join(taken[:10])))
    else:
        print("  ids: %d, none of them the corpus's (%d)" % (len(entities), len(corpus)))

    dangling = sorted(pointed_at(entities, set()) | pointed_at(corrections, set()))
    dangling = [h for h in dangling if h not in entities and h not in corpus]
    if dangling:
        fail = 1
        print("  REFERENCES — %d ids the layer points at are in neither the layer nor the corpus: %s"
              % (len(dangling), ", ".join(dangling[:10])))
    else:
        print("  references: every id the layer points at resolves (layer or corpus)")

    # a reference written with both an id and a name: the name must be the one the entity at
    # that id carries NOW. Without this a corpus rename (the dots taken out of 893 names,
    # 2026-09-25) leaves every stale name standing, because the hash alone still resolves.
    name_at = {h: nm for h, (nm, _bk) in corpus_all.items()}
    name_at.update({h: e["name"] for h, e in entities.items()})
    pairs = hashed_pairs(book_blob.get("entities"), []) + hashed_pairs(index_blob.get("corrections"), [])
    stale = sorted({(w, h, nm, name_at[h]) for w, h, nm in pairs if h in name_at and name_at[h] != nm})
    if stale:
        fail = 1
        print("  STALE — %d references name an id by a name it does not carry:" % len(stale))
        for w, h, nm, now in stale[:25]:
            print("    %s %r is %r (in %s)" % (h, nm, now, w))
    else:
        print("  pairs: %d references by id and name, every name the one its id carries" % len(pairs))

    by_name = {}
    for h, (nm, bk) in corpus_all.items():
        by_name.setdefault(nm, []).append((h, bk))
    for h, e in entities.items():
        by_name.setdefault(e["name"], []).append((h, a.id))
    refs = named_refs(book_blob.get("entities"), index_blob.get("corrections"), a.id)
    unknown = [(w, nm) for w, nm in refs if nm not in by_name]
    if unknown:
        fail = 1
        print("  NAMES — %d references name nothing in the layer or the corpus:" % len(unknown))
        for w, nm in unknown[:25]:
            print("    %r (%s)" % (nm, w))
    else:
        print("  names: %d references by name, every one names an entity" % len(refs))
    for w, nm in sorted(set(refs)):
        hits = by_name.get(nm, [])
        if len(hits) > 1:
            pick = (next((x for x in hits if x[1] == a.id), None)
                    or next((x for x in hits if x[1] == "core"), None) or hits[0])
            print("    note — %r (%s) names %d entities; the pages resolve it to %s in %s"
                  % (nm, w, len(hits), pick[0], pick[1]))
    print("build_layer: %s" % ("FAILED" if fail else "OK"))
    return fail


if __name__ == "__main__":
    sys.exit(main())
